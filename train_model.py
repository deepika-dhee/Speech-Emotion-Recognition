from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    classification_report, confusion_matrix
)

APP_DIR = Path(__file__).resolve().parent
ARTIFACT_DIR = APP_DIR / "artifacts"
CSV_PATH = APP_DIR / "data" / "features_tess.csv"
WINDOWS_CSV_PATH = Path(r"E:\gda\Tess\features_tess.csv")

FEATURE_NAMES = (
    [name for i in range(1, 14) for name in (f"mfcc_{i}_mean", f"mfcc_{i}_std")]
    + ["energy_mean", "energy_std", "zcr_mean", "centroid_mean", "bandwidth_mean", "rolloff_mean"]
)

def fit_gda(X, y):
    classes = np.unique(y)
    n_samples, n_features = X.shape
    priors, means = {}, {}
    for label in classes:
        x_class = X[y == label]
        priors[str(label)] = float(len(x_class) / n_samples)
        means[str(label)] = np.mean(x_class, axis=0)

    covariance = np.zeros((n_features, n_features))
    for label in classes:
        x_class = X[y == label]
        centered = x_class - means[str(label)]
        covariance += centered.T @ centered
    covariance /= n_samples
    covariance += 1e-6 * np.eye(n_features)

    sign, log_det = np.linalg.slogdet(covariance)
    if sign <= 0:
        raise ValueError("Shared covariance matrix is not positive definite.")
    covariance_inverse = np.linalg.inv(covariance)
    return {
        "classes": [str(x) for x in classes],
        "priors": priors,
        "means": means,
        "covariance": covariance,
        "covariance_inverse": covariance_inverse,
        "log_det": float(log_det),
        "feature_names": FEATURE_NAMES,
    }

def gda_scores(X, model):
    scores = []
    for label in model["classes"]:
        mean = model["means"][label]
        diff = X - mean
        mahalanobis = np.sum((diff @ model["covariance_inverse"]) * diff, axis=1)
        scores.append(
            np.log(model["priors"][label]) - 0.5 * mahalanobis - 0.5 * model["log_det"]
        )
    return np.column_stack(scores)

def gda_predict(X, model):
    scores = gda_scores(X, model)
    indices = np.argmax(scores, axis=1)
    return np.array(model["classes"])[indices]

def summarize(y_true, y_pred):
    return {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "macro_precision": float(precision_score(y_true, y_pred, average="macro", zero_division=0)),
        "macro_recall": float(recall_score(y_true, y_pred, average="macro", zero_division=0)),
        "macro_f1": float(f1_score(y_true, y_pred, average="macro", zero_division=0)),
    }

def main():
    ARTIFACT_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = CSV_PATH if CSV_PATH.exists() else WINDOWS_CSV_PATH
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Could not find features_tess.csv. Place it at {CSV_PATH} or check {WINDOWS_CSV_PATH}."
        )
    df = pd.read_csv(csv_path)

    required = set(FEATURE_NAMES + ["emotion"])
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(
            "The CSV is missing required columns: " + ", ".join(missing) +
            ". Check that this is the feature CSV generated by the original notebook."
        )

    # Match the notebook's filtering rule where speaker metadata is present.
    if "speaker" in df.columns:
        df = df[df["speaker"].isin(["OAF", "YAF"])].copy()

    df = df.dropna(subset=list(FEATURE_NAMES) + ["emotion"]).copy()
    X = df.loc[:, FEATURE_NAMES].to_numpy(dtype=float)
    y = df["emotion"].astype(str).to_numpy()
    if len(np.unique(y)) < 2:
        raise ValueError("At least two emotion classes are required to train GDA.")

    # Reproduce the notebook's stratified 80:20 split.
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    gda_model = fit_gda(X_train_scaled, y_train)
    gda_pred = gda_predict(X_test_scaled, gda_model)

    # Fit comparison models only on the training split.
    lda = LinearDiscriminantAnalysis()
    lda.fit(X_train_scaled, y_train)
    lda_pred = lda.predict(X_test_scaled)

    logistic = LogisticRegression(max_iter=3000, random_state=42)
    logistic.fit(X_train_scaled, y_train)
    logistic_pred = logistic.predict(X_test_scaled)

    labels = gda_model["classes"]
    report = classification_report(
        y_test, gda_pred, labels=labels, output_dict=True, zero_division=0
    )
    cm = confusion_matrix(y_test, gda_pred, labels=labels)
    evaluations = {
        "GDA": summarize(y_test, gda_pred),
        "LDA": summarize(y_test, lda_pred),
        "Logistic Regression": summarize(y_test, logistic_pred),
    }
    evaluations["GDA"]["train_samples"] = int(len(X_train))
    evaluations["GDA"]["test_samples"] = int(len(X_test))
    evaluations["GDA"]["feature_count"] = int(X_train.shape[1])
    evaluations["GDA"]["class_count"] = int(len(labels))

    joblib.dump(gda_model, ARTIFACT_DIR / "gda_model.joblib")
    joblib.dump(scaler, ARTIFACT_DIR / "scaler.joblib")
    joblib.dump(lda, ARTIFACT_DIR / "lda_model.joblib")
    joblib.dump(logistic, ARTIFACT_DIR / "logistic_model.joblib")
    with open(ARTIFACT_DIR / "evaluation.json", "w", encoding="utf-8") as f:
        json.dump(evaluations, f, indent=2)
    pd.DataFrame(report).T.to_csv(ARTIFACT_DIR / "classification_report.csv")
    pd.DataFrame(cm, index=labels, columns=labels).to_csv(ARTIFACT_DIR / "confusion_matrix.csv")
    pd.DataFrame({
        "true_emotion": y_test,
        "gda_prediction": gda_pred,
        "lda_prediction": lda_pred,
        "logistic_prediction": logistic_pred,
    }).to_csv(ARTIFACT_DIR / "heldout_predictions.csv", index=False)

    print(f"Dataset: {csv_path}")
    print(f"Training rows: {len(X_train)} | Held-out test rows: {len(X_test)}")
    print(f"Feature count: {len(FEATURE_NAMES)}")
    print("\nHeld-out results (new reproducible run):")
    for name, metrics in evaluations.items():
        print(
            f"{name}: accuracy={metrics['accuracy']:.4f}, "
            f"macro_precision={metrics['macro_precision']:.4f}, "
            f"macro_recall={metrics['macro_recall']:.4f}, "
            f"macro_f1={metrics['macro_f1']:.4f}"
        )
    print(f"\nSaved model artifacts to: {ARTIFACT_DIR}")

if __name__ == "__main__":
    main()
